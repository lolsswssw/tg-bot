async def love_command(event, client, args):
    heart = random.choice(HEARTS)
    msg = random.choice(LOVE_MESSAGES)
    animation = f"{heart} " * 10
    await event.reply(f"{animation}\n\n{msg}\n\n{animation}")


async def troll_command(event, client, args):
    selected = random.sample(INSULTS, min(10, len(INSULTS)))
    for insult in selected:
        await event.reply(insult)
        await asyncio.sleep(0.5)


async def spam_command(event, client, args):
    text = " ".join(args) if args else "Спам!"
    for i in range(10):
        await event.reply(f"{i+1}. {text}")
        await asyncio.sleep(1)
